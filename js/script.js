const projectsGrid = document.getElementById('projectsGrid');
const header = document.querySelector('.header');
const screenshotsContainer = document.getElementById('screenshotsContainer');
const screenshotsDiv = document.getElementById('screenshots');
const googlePlayBtn = document.getElementById('googlePlayBtn');
let currentBgColor = '#1a1a2e';

// Populate projects
projects.forEach((project) => {
    const projectContainer = document.createElement('div');
    projectContainer.className = 'project-container';

    const projectIcon = document.createElement('div');
    projectIcon.className = 'project-icon';
    projectIcon.innerHTML = `<img src="${project.image}" alt="${project.name}">`;

    const projectName = document.createElement('span');
    projectName.className = 'project-name';
    projectName.textContent = project.name;

    projectIcon.addEventListener('click', (e) => {
        e.stopPropagation();

        document.querySelectorAll('.project-icon').forEach(icon => {
            icon.classList.remove('active');
        });

        projectIcon.classList.add('active');

        currentBgColor = project.bgColor;
        document.body.style.backgroundColor = currentBgColor;

        // Hide header, show screenshots
        header.classList.add('hidden');
        if (project.screenshots && project.screenshots.length >= 4) {
            document.getElementById('projectTitle').textContent = project.name;
            
            screenshotsDiv.innerHTML = project.screenshots
                .slice(0, 4)
                .map(src => `<img src="${src}" alt="screenshot">`)
                .join('');
            
            if (project.isVertical) {
                screenshotsDiv.classList.add('vertical');
            } else {
                screenshotsDiv.classList.remove('vertical');
            }
            
            screenshotsContainer.classList.add('active');
            
            googlePlayBtn.href = project.playStoreUrl;
            googlePlayBtn.classList.add('active');

            document.getElementById('download-text').textContent =  `${project.downloads}`;
        }
    });

    projectContainer.appendChild(projectIcon);
    projectContainer.appendChild(projectName);
    projectsGrid.appendChild(projectContainer);
});

// Click anywhere to deselect
document.addEventListener('click', (e) => {
    if (!e.target.closest('.project-container') && !e.target.closest('.google-play-btn')) {
        document.querySelectorAll('.project-icon').forEach(icon => {
            icon.classList.remove('active');
        });
        header.classList.remove('hidden');
        screenshotsContainer.classList.remove('active');
        googlePlayBtn.classList.remove('active');
        document.getElementById('projectTitle').textContent = '';
        currentBgColor = '#282828';
        document.body.style.backgroundColor = currentBgColor;
    }
});